// 🆕 تطبيع النص العربي للبحث المرن — بيوحّد أشكال الهمزة/التاء المربوطة/الألف المقصورة
// ويشيل التشكيل والتطويل، عشان "أنيميا"/"انيميا" أو "دواء"/"دوايه" ترجع نفس النتيجة.
export function normalizeArabicText(text: any): string {
    if (!text) return "";
    return String(text)
        .toLowerCase()
        .replace(/[\u064B-\u065F\u0670]/g, "")   // إزالة التشكيل
        .replace(/[إأآا]/g, "ا")                  // توحيد الألف
        .replace(/ى/g, "ي")                       // توحيد الألف المقصورة/الياء
        .replace(/ة/g, "ه")                       // توحيد التاء المربوطة
        .replace(/ـ/g, "")                        // إزالة التطويل (الكشيدة)
        .trim();
}